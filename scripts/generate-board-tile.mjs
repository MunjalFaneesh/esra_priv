#!/usr/bin/env node
/**
 * Generates public/board-tile.svg — the routing texture behind the site.
 *
 * Deliberately sparse: a few long traces with 45-degree jogs, a dimmer
 * bottom-layer run, the odd stitching via, and one small row of solder
 * joints. It should read as "this is a board" at a glance and then get
 * out of the way of the content.
 *
 * Seamless by construction: only continuous traces cross the tile edges,
 * and each one leaves an edge at the same coordinate it enters the
 * opposite edge. Everything else sits well inside the tile, so nothing
 * is ever clipped at a seam.
 *
 * The tile is large (960px, 40 grid cells) so the repeat is hard to spot.
 * Colours are baked in because CSS variables do not reach into a
 * background-image SVG; keep them in step with tokens.css.
 *
 * Run: node scripts/generate-board-tile.mjs
 */
import { writeFileSync } from 'node:fs';

const W = 960;
const H = 960;

/** Master strength of the whole texture against the page. */
const STRENGTH = 0.5;

const TRACE = '#4a78bd'; // --trace
const PAD = '#e3d3ad'; // --pad
const SILK = '#f2ede1'; // --ink
const HOLE = '#04070c';

const TOP = { stroke: TRACE, opacity: 0.6, width: 2.5 };
const BOTTOM = { stroke: TRACE, opacity: 0.28, width: 2.5 };
const NET = { stroke: TRACE, opacity: 0.6, width: 2 };

const out = [];

const trace = (d, s = NET) =>
  out.push(
    `<path d="${d}" fill="none" stroke="${s.stroke}" stroke-opacity="${s.opacity}" ` +
      `stroke-width="${s.width}" stroke-linecap="round" stroke-linejoin="round"/>`
  );

const via = (x, y) =>
  out.push(
    `<circle cx="${x}" cy="${y}" r="5" fill="${TRACE}" fill-opacity="0.75"/>` +
      `<circle cx="${x}" cy="${y}" r="2.2" fill="${HOLE}"/>`
  );

const joint = (x, y, square = false) => {
  out.push(
    square
      ? `<rect x="${x - 8}" y="${y - 8}" width="16" height="16" fill="${PAD}" fill-opacity="0.5"/>`
      : `<circle cx="${x}" cy="${y}" r="8" fill="${PAD}" fill-opacity="0.5"/>`
  );
  out.push(
    `<circle cx="${x - 2.5}" cy="${y - 2.5}" r="2.2" fill="${SILK}" fill-opacity="0.25"/>` +
      `<circle cx="${x}" cy="${y}" r="3.2" fill="${HOLE}"/>`
  );
};

const testPoint = (x, y) =>
  out.push(
    `<circle cx="${x}" cy="${y}" r="6" fill="none" stroke="${PAD}" stroke-opacity="0.5" stroke-width="2"/>`
  );

/* Bottom layer first. Vertical runs: each exits the bottom edge at the
   x it entered the top. */
trace('M744 0 V360 L792 408 V600 L744 648 V960', BOTTOM);
trace('M120 0 V432 L168 480 V720 L120 768 V960', BOTTOM);

/* Top layer. A routed pair that jogs down together and back, and a
   single run lower down. Each exits the right edge at the y it entered
   the left. */
trace('M0 168 H312 L360 216 H600 L648 168 H960', TOP);
trace('M0 192 H288 L336 240 H624 L672 192 H960', TOP);
trace('M0 696 H408 L456 744 H720 L768 696 H960', TOP);

/* A few branches, each ending in a via. */
trace('M480 216 V288');
via(480, 288);
trace('M240 696 V624 L264 600');
via(264, 600);
trace('M600 744 V816 L624 840');
via(624, 840);

/* One small pin header with its solder joints, tied into the board. */
[336, 360, 384, 408].forEach((x, i) => joint(x, 888, i === 0));
trace('M336 880 V840 L312 816');
via(312, 816);

/* Stitching vias and a test point, spread so the repeat stays quiet. */
via(888, 552);
via(552, 456);
via(72, 312);
testPoint(840, 840);

const svg =
  `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">` +
  `<!-- Generated by scripts/generate-board-tile.mjs — edit the script, not this file. -->` +
  `<g opacity="${STRENGTH}">` +
  out.join('') +
  `</g></svg>\n`;

writeFileSync(new URL('../public/board-tile.svg', import.meta.url), svg);
console.log(`public/board-tile.svg — ${out.length} elements, ${svg.length} bytes`);
